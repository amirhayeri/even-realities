#!/usr/bin/env bash
# Writes BioHUDWatch/Config.swift from ../app/.env so the watch uses the same endpoint and token.
set -euo pipefail
cd "$(dirname "$0")"
ENV=../app/.env
[ -f "$ENV" ] || { echo "missing $ENV"; exit 1; }
EP=$(grep '^VITE_HUD_ENDPOINT=' "$ENV" | cut -d= -f2- | tr -d '[:space:]"'"'"'')
TK=$(grep '^VITE_HUD_TOKEN=' "$ENV" | cut -d= -f2- | tr -d '[:space:]"'"'"'')
TEAM=$(grep '^DEVELOPMENT_TEAM=' "$ENV" | cut -d= -f2- | tr -d '[:space:]"'"'"'' || true)
BID=$(grep '^WATCH_BUNDLE_ID=' "$ENV" | cut -d= -f2- | tr -d '[:space:]"'"'"'' || true)
# xcodegen reads these from the environment when it expands project.yml
export DEVELOPMENT_TEAM="${TEAM:-}"
export WATCH_BUNDLE_ID="${BID:-com.example.biohud.watchos}"
echo "team=${DEVELOPMENT_TEAM:-<set in Xcode>} bundle=$WATCH_BUNDLE_ID"
cat > BioHUDWatch/Config.swift <<SWIFT
// Generated by make-config.sh from ../app/.env. Do not commit.
enum Config {
    static let endpoint = "$EP"
    static let token = "$TK"
}
SWIFT
echo "wrote BioHUDWatch/Config.swift for $EP"
[ -n "$WATCH_BUNDLE_ID" ] && command -v xcodegen >/dev/null && xcodegen generate >/dev/null && echo "regenerated BioHUDWatch.xcodeproj"
